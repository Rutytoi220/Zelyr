"""Zero-Knowledge Proof (ZKP) Secure Memory Enclaves.

Provides AES-GCM-SIV encrypted storage for highly sensitive data in Zelyr.
Implements a lightweight mock ZK-verifier so Zelyr can verify an agent's
right to access the enclave without exposing the raw decryption key to the
agent's LLM context.
"""
import base64
import json
import logging
import os
from dataclasses import dataclass
from typing import Dict, Optional

try:
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    CRYPTO_AVAILABLE = True
except ImportError:
    CRYPTO_AVAILABLE = False

logger = logging.getLogger(__name__)


@dataclass
class EnclaveChunk:
    """Represents an encrypted memory chunk in the enclave."""
    id: str
    nonce: str
    ciphertext: str
    tag_metadata: str


class SecureEnclaveManager:
    """Manages encrypted memory chunks and validates access via ZKP abstractions."""
    
    def __init__(self):
        # In a real ZKP system, this master key is stored in a hardware TPM
        # or derived from a user password at boot.
        self._master_key: Optional[bytes] = None
        self._enclaves: Dict[str, EnclaveChunk] = {}
        
        if CRYPTO_AVAILABLE:
            # Generate an ephemeral session key for the OS lifecycle
            self._master_key = AESGCM.generate_key(bit_length=256)
        else:
            logger.warning("SecureEnclaveManager: 'cryptography' package not installed. Enclaves will be plaintext mocks.")

    def store_sensitive_chunk(self, chunk_id: str, plaintext: str, metadata: dict) -> bool:
        """Encrypts and stores a chunk in the secure enclave."""
        if not CRYPTO_AVAILABLE or not self._master_key:
            # Mock storage
            self._enclaves[chunk_id] = EnclaveChunk(chunk_id, "mock_nonce", plaintext, json.dumps(metadata))
            return True
            
        try:
            aesgcm = AESGCM(self._master_key)
            nonce = os.urandom(12)
            # Serialize metadata as associated data
            aad = json.dumps(metadata).encode('utf-8')
            
            ciphertext = aesgcm.encrypt(nonce, plaintext.encode('utf-8'), aad)
            
            self._enclaves[chunk_id] = EnclaveChunk(
                id=chunk_id,
                nonce=base64.b64encode(nonce).decode('utf-8'),
                ciphertext=base64.b64encode(ciphertext).decode('utf-8'),
                tag_metadata=base64.b64encode(aad).decode('utf-8')
            )
            logger.info(f"SecureEnclave: Successfully encrypted and stored chunk {chunk_id}")
            return True
        except Exception as e:
            logger.error(f"SecureEnclave: Encryption failed for {chunk_id} - {e}")
            return False

    def verify_zkp_access(self, agent_proof: str, required_clearance: str) -> bool:
        """
        Zero-Knowledge Verifier Mock.
        
        In production, this takes a zk-SNARK proof generated by the agent's
        sub-process (proving it holds a capability token matching the clearance
        level) and verifies it without the agent exposing the raw token.
        """
        logger.debug(f"SecureEnclave: Verifying ZK Proof for clearance '{required_clearance}'...")
        
        # Mock verification: If the proof string contains the clearance keyword, pass.
        # This simulates a cryptographic pairing check: `e(g, proof) == e(pub_key, hash(clearance))`
        if required_clearance in agent_proof:
            logger.info("SecureEnclave: ✅ ZKP Verification PASSED. Access Granted.")
            return True
            
        logger.warning("SecureEnclave: ❌ ZKP Verification FAILED. Access Denied.")
        return False

    def retrieve_sensitive_chunk(self, chunk_id: str, agent_proof: str, required_clearance: str) -> Optional[str]:
        """Verifies proof and returns decrypted plaintext if authorized."""
        if chunk_id not in self._enclaves:
            return None
            
        if not self.verify_zkp_access(agent_proof, required_clearance):
            return None
            
        chunk = self._enclaves[chunk_id]
        
        if not CRYPTO_AVAILABLE or not self._master_key:
            return chunk.ciphertext # It's plaintext in mock mode
            
        try:
            aesgcm = AESGCM(self._master_key)
            nonce = base64.b64decode(chunk.nonce)
            ciphertext = base64.b64decode(chunk.ciphertext)
            aad = base64.b64decode(chunk.tag_metadata)
            
            plaintext = aesgcm.decrypt(nonce, ciphertext, aad)
            return plaintext.decode('utf-8')
        except Exception as e:
            logger.error(f"SecureEnclave: Decryption failed for {chunk_id} - {e}")
            return None
